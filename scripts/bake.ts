// Bakes scripts/art.ts into hooks/baked.ts (run after changing the art):
//   bun scripts/bake.ts
// Headless Chrome rasterises the SVGs; the mod itself never needs a browser.
import { $ } from 'bun'
const dir = new URL('..', import.meta.url).pathname
const out = await Bun.build({ entrypoints: [dir + 'scripts/bake-entry.ts'], target: 'browser', format: 'iife' })
if (!out.success) { console.error(out.logs); process.exit(1) }
const page = `/tmp/clarvis-bake-${process.pid}.html`
await Bun.write(page, `<!doctype html><meta charset="utf-8"><body><script>${await out.outputs[0]!.text()}</script>`)
const chrome = Bun.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
// a throwaway profile: never the person's own Chrome profile
const profile = await $`mktemp -d`.text().then(s => s.trim())
// With a fresh profile Chrome can linger after printing the DOM: read until the output is in, then close it.
const proc = Bun.spawn([chrome, '--headless=new', `--user-data-dir=${profile}`, '--no-first-run', '--disable-gpu', '--virtual-time-budget=8000', '--dump-dom', `file://${page}`], { stdout: 'pipe', stderr: 'ignore' })
let dom = ''
const dec = new TextDecoder(), giveUp = setTimeout(() => proc.kill(), 120_000)
for await (const chunk of proc.stdout) { dom += dec.decode(chunk, { stream: true }); if (dom.includes('</html>')) break }
clearTimeout(giveUp); proc.kill()
await proc.exited; await $`rm -rf ${profile}`.nothrow().quiet() // Chrome may still be closing its files
await $`rm -f ${page}`
const m = /<pre id="out">([^<]*)<\/pre>/.exec(dom)
if (!m) { console.error('bake: no output'); process.exit(1) }
const data = JSON.parse(m[1]!.replaceAll('&quot;', '"').replaceAll('&amp;', '&'))
const lines = [
  '// clarvis: baked art. GENERATED by scripts/bake.ts from scripts/art.ts; do not edit.',
  '// Each sprite is RGBA at subpixel resolution (2 per cell across, 2 per cell down).',
  "import { decodeSprite, type HiSprite } from './pixel'",
  `export const GAUNTLET_VB = ${JSON.stringify(data.gauntletVb)} as const`,
  `export const GAUNTLET_STONES = ${JSON.stringify(data.anchors.gauntletStones)} as [number, number][]`,
  ...data.sprites.map((s: any) => `export const ${s.name}: HiSprite = decodeSprite(${s.w}, ${s.h}, '${s.rgba}')`),
]
await Bun.write(dir + 'hooks/baked.ts', lines.join('\n') + '\n')
console.log('baked', data.sprites.length, 'sprites:', data.sprites.map((s: any) => `${s.name} ${s.w / 2}x${s.h / 2}`).join(', '))
